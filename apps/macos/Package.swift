// swift-tools-version:6.0
import PackageDescription

// Swift 5 language mode on purpose: the targets are built and tested headlessly, and strict
// Sendable checking would add friction without changing behaviour. Revisit per target later.
//
// One target per area so parallel work never shares a module: a half-written file in one area
// cannot break another area's build.
//
//   Models  -> wire DTOs, JSON coding            (no dependencies)
//   Store   -> SQLite persistence (GRDB)         (Models)
//   JS      -> JavaScriptCore bridge             (Models)
//   Network -> API client, token storage         (Models)
//   Sync    -> outbox + pull engine              (Models, Store, Network)
//   Platform-> notification planning, menu bar model (Models, Store)
//   Core    -> view models                       (re-exports all of the above)
//   App     -> SwiftUI shell                     (Core)
let swift5: [SwiftSetting] = [.swiftLanguageMode(.v5)]

let package = Package(
    name: "Husrevity",
    platforms: [.macOS(.v14)],
    products: [
        .library(name: "HusrevityCore", targets: ["HusrevityCore"]),
        .executable(name: "HusrevityApp", targets: ["HusrevityApp"]),
    ],
    dependencies: [
        .package(url: "https://github.com/groue/GRDB.swift.git", from: "7.0.0"),
        .package(url: "https://github.com/sindresorhus/KeyboardShortcuts.git", from: "2.0.0"),
    ],
    targets: [
        .target(name: "HusrevityModels", swiftSettings: swift5),
        .target(
            name: "HusrevityStore",
            dependencies: ["HusrevityModels", .product(name: "GRDB", package: "GRDB.swift")],
            swiftSettings: swift5
        ),
        .target(
            name: "HusrevityJS",
            dependencies: ["HusrevityModels"],
            resources: [.copy("Resources")],
            swiftSettings: swift5
        ),
        .target(name: "HusrevityNetwork", dependencies: ["HusrevityModels"], swiftSettings: swift5),
        .target(
            name: "HusrevitySync",
            dependencies: ["HusrevityModels", "HusrevityStore", "HusrevityNetwork"],
            swiftSettings: swift5
        ),
        .target(
            name: "HusrevityPlatform",
            dependencies: ["HusrevityModels", "HusrevityStore"],
            swiftSettings: swift5
        ),
        .target(
            name: "HusrevityCore",
            dependencies: [
                "HusrevityModels", "HusrevityStore", "HusrevityJS", "HusrevityNetwork",
                "HusrevitySync", "HusrevityPlatform",
            ],
            swiftSettings: swift5
        ),
        .executableTarget(
            name: "HusrevityApp",
            dependencies: [
                "HusrevityCore",
                .product(name: "KeyboardShortcuts", package: "KeyboardShortcuts"),
            ],
            swiftSettings: swift5
        ),

        // Real API responses shared by every test target. Regenerated by the API's
        // fixtures.integration.spec.ts; never edit by hand.
        .target(
            name: "HusrevityTestSupport",
            resources: [.copy("Fixtures")],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityModelsTests",
            dependencies: ["HusrevityModels", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityStoreTests",
            dependencies: ["HusrevityStore", "HusrevityModels", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityJSTests",
            dependencies: ["HusrevityJS"],
            exclude: ["Fixtures"],  // read through #filePath, not as a bundle resource
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityNetworkTests",
            dependencies: ["HusrevityNetwork", "HusrevityModels", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevitySyncTests",
            dependencies: [
                "HusrevitySync", "HusrevityStore", "HusrevityNetwork", "HusrevityModels",
                "HusrevityTestSupport",
            ],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityPlatformTests",
            dependencies: ["HusrevityPlatform", "HusrevityStore", "HusrevityModels", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
        // Runs against a real API + disposable Postgres started by scripts/e2e.sh; every test is
        // skipped unless HUSREVITY_E2E_URL is set, so a plain `swift test` stays offline.
        .testTarget(
            name: "HusrevityE2ETests",
            dependencies: ["HusrevityCore", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
        .testTarget(
            name: "HusrevityCoreTests",
            dependencies: ["HusrevityCore", "HusrevityTestSupport"],
            swiftSettings: swift5
        ),
    ]
)
